struct agy_orchestrator agy_orchestrator;
static struct agy_agent agents[AGY_MAX_AGENTS];
static uint32_t next_agent_id = 1;

static struct agy_agent *agy_find_by_name(const char *name) {
    if (!name) return NULL;
    for (int i = 0; i < AGY_MAX_AGENTS; i++) {
        if (agents[i].state != AGENT_UNUSED && strcmp(agents[i].name, name) == 0) {
            return &agents[i];
        }
    }
    return NULL;
}

static struct agy_agent *agy_find_by_pid(int32_t pid) {
    if (pid <= 0) return NULL;
    for (int i = 0; i < AGY_MAX_AGENTS; i++) {
        if (agents[i].state != AGENT_UNUSED && agents[i].pid == pid) {
            return &agents[i];
        }
    }
    return NULL;
}

