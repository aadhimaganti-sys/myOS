static void agy_worker_trampoline(void) {
    struct task *cur = get_current_task();
    if (!cur) {
        task_exit();
        return;
    }

    struct agy_agent *agent = agy_find_by_pid((int32_t)cur->pid);
    if (!agent) {
        agent = agy_find_by_name(cur->name);
    }
    if (!agent) {
        kprintf("[AGY:ERROR] No agent found for task PID %u ('%s')\n", cur->pid, cur->name);
        task_exit();
        return;
    }

    kprintf("[AGY:%s] Worker thread activated (PID: %u, Tick: %lu)\n",
            agent->name, cur->pid, timer_get_ticks());

    /* Phase 1: Thinking */
    agent->state = AGENT_THINKING;
    agent->last_tick = timer_get_ticks();
    agy_orchestrator.total_tokens += 480;
    strncpy(agent->last_message, "Analyzing goal context and selecting tools...", sizeof(agent->last_message) - 1);
    agent->last_message[sizeof(agent->last_message) - 1] = '\0';
    kprintf("[AGY:%s] [THINKING] Model: %s | Tokens: +480 | Goal: \"%s\"\n",
            agent->name, agy_orchestrator.active_model, agent->current_goal);

    task_yield();

    /* Phase 2: Running steps */
    agent->state = AGENT_RUNNING;
    if (agent->worker_fn) {
        agent->steps_done = 1;
        agent->last_tick = timer_get_ticks();
        agy_orchestrator.total_tokens += 350;
        strncpy(agent->last_message, "Executing custom agent worker routine", sizeof(agent->last_message) - 1);
        agent->last_message[sizeof(agent->last_message) - 1] = '\0';
        kprintf("[AGY:%s] [RUNNING] Executing custom worker routine...\n", agent->name);
        agent->worker_fn();
        agent->steps_done = agent->steps_total;
        task_yield();
    } else {
        while (agent->steps_done < agent->steps_total) {
            agent->steps_done++;
            agent->last_tick = timer_get_ticks();
            agy_orchestrator.total_tokens += 320;

            if (agent->steps_done == 1) {
                strncpy(agent->last_message, "Step 1/3: Context retrieval and architecture inspection", sizeof(agent->last_message) - 1);
            } else if (agent->steps_done == 2) {
                strncpy(agent->last_message, "Step 2/3: Generating implementation & executing solution", sizeof(agent->last_message) - 1);
            } else {
                strncpy(agent->last_message, "Step 3/3: Validating execution and generating artifact", sizeof(agent->last_message) - 1);
            }
            agent->last_message[sizeof(agent->last_message) - 1] = '\0';

            kprintf("[AGY:%s] [RUNNING] Step %u/%u: %s\n",
                    agent->name, agent->steps_done, agent->steps_total, agent->last_message);
            task_yield();
        }
    }

    /* Phase 3: Completed */
    agent->state = AGENT_COMPLETED;
    agent->last_tick = timer_get_ticks();
    agy_orchestrator.total_tokens += 220;
    agy_orchestrator.tasks_done++;

    /* Generate artifact in ramfs */
    agy_generate_artifact(agent);

    strncpy(agent->last_message, "Goal completed. Artifact saved to ramfs.", sizeof(agent->last_message) - 1);
    agent->last_message[sizeof(agent->last_message) - 1] = '\0';
    kprintf("[AGY:%s] [COMPLETED] Task finished! Artifact saved to ramfs. (Total tokens: %lu)\n",
            agent->name, agy_orchestrator.total_tokens);

    agent->pid = -1;
    task_exit();
}

void agy_init(void) {
    memset(agents, 0, sizeof(agents));
    next_agent_id = 1;

    strncpy(agy_orchestrator.active_model, "gemini-2.5-flash", sizeof(agy_orchestrator.active_model) - 1);
    agy_orchestrator.active_model[sizeof(agy_orchestrator.active_model) - 1] = '\0';
    agy_orchestrator.total_tokens = 0;
    agy_orchestrator.active_agents = 0;
    agy_orchestrator.tasks_done = 0;

    kprintf("\n====================================================================\n");
    kprintf("       GOOGLE ANTIGRAVITY AGENT ENGINE INITIALIZING                 \n");
    kprintf("====================================================================\n");

    /* Pre-register standard agents at boot */
    agy_register_agent("Orchestrator",   "Lead Systems Architect",     NULL);
    agy_register_agent("ResearchAgent",  "Codebase & Docs Researcher",  NULL);
    agy_register_agent("CodeAgent",      "Bare-Metal Kernel Developer", NULL);
    agy_register_agent("ReviewerAgent",  "Code & Safety Auditor",       NULL);

    kprintf("[+] Antigravity Agent Engine initialized (Active Model: %s, 4 Core Agents Ready)\n",
            agy_orchestrator.active_model);
}

int agy_register_agent(const char *name, const char *role, void (*worker_fn)(void)) {
    if (!name || !role) return -1;

    /* Check if already registered */
    for (int i = 0; i < AGY_MAX_AGENTS; i++) {
        if (agents[i].state != AGENT_UNUSED && strcmp(agents[i].name, name) == 0) {
            return (int)agents[i].id;
        }
    }

    /* Find free slot */
    int slot = -1;
    for (int i = 0; i < AGY_MAX_AGENTS; i++) {
        if (agents[i].state == AGENT_UNUSED) {
            slot = i;
            break;
        }
    }
    if (slot == -1) {
        kprintf("[AGY:ERROR] Agent table full, cannot register '%s'\n", name);
        return -1;
    }

    struct agy_agent *a = &agents[slot];
    memset(a, 0, sizeof(struct agy_agent));

    a->id = next_agent_id++;
    strncpy(a->name, name, sizeof(a->name) - 1);
    a->name[sizeof(a->name) - 1] = '\0';

    strncpy(a->role, role, sizeof(a->role) - 1);
    a->role[sizeof(a->role) - 1] = '\0';

    a->state = AGENT_IDLE;
    a->pid = -1;
    a->steps_total = 0;
    a->steps_done = 0;
    a->last_tick = timer_get_ticks();
    a->worker_fn = worker_fn;
    strncpy(a->last_message, "Agent idle, awaiting assignment", sizeof(a->last_message) - 1);
    a->last_message[sizeof(a->last_message) - 1] = '\0';

    kprintf("[AGY] Registered agent #%u: '%s' [%s]\n", a->id, a->name, a->role);
    return (int)a->id;
}

int agy_prompt(const char *agent_name, const char *goal) {
    if (!agent_name || !goal) return -1;

    struct agy_agent *agent = agy_find_by_name(agent_name);
    if (!agent) {
        kprintf("[AGY:ERROR] Agent '%s' not found!\n", agent_name);
        return -1;
    }

    if (agent->state == AGENT_THINKING || agent->state == AGENT_RUNNING) {
        kprintf("[AGY:WARN] Agent '%s' is busy (state: %d)\n", agent->name, agent->state);
        return -2;
    }

    strncpy(agent->current_goal, goal, sizeof(agent->current_goal) - 1);
    agent->current_goal[sizeof(agent->current_goal) - 1] = '\0';

    agent->state = AGENT_THINKING;
    agent->steps_total = 3;
    agent->steps_done = 0;
    agent->last_tick = timer_get_ticks();
    strncpy(agent->last_message, "Prompt received. Thinking...", sizeof(agent->last_message) - 1);
    agent->last_message[sizeof(agent->last_message) - 1] = '\0';

    kprintf("[AGY] Prompted agent '%s' with goal: \"%s\"\n", agent->name, agent->current_goal);

    /* Spawn background worker thread via kernel scheduler */
    int pid = task_create(agent->name, agy_worker_trampoline, 3);
    if (pid >= 0) {
        agent->pid = pid;
    } else {
        kprintf("[AGY:WARN] Could not create task for '%s'; will step cooperatively\n", agent->name);
        agent->pid = -1;
    }

    return 0;
}

int agy_spawn(const char *name, const char *role) {
    if (!name || !role) return -1;
    for (int i = 0; i < AGY_MAX_AGENTS; i++) {
        if (agents[i].state != AGENT_UNUSED && strcmp(agents[i].name, name) == 0) {
            return (int)agents[i].id;
        }
    }
    return agy_register_agent(name, role, NULL);
}

void agy_set_model(const char *model_name) {
    if (!model_name || strlen(model_name) == 0) return;
    strncpy(agy_orchestrator.active_model, model_name, sizeof(agy_orchestrator.active_model) - 1);
    agy_orchestrator.active_model[sizeof(agy_orchestrator.active_model) - 1] = '\0';
    kprintf("[AGY] Active model set to '%s'\n", agy_orchestrator.active_model);
}

const char *agy_get_model(void) {
    return agy_orchestrator.active_model;
}

struct agy_agent *agy_get_agents(int *count) {
    if (count) {
        int cnt = 0;
        for (int i = 0; i < AGY_MAX_AGENTS; i++) {
            if (agents[i].state != AGENT_UNUSED) {
                cnt++;
            }
        }
        *count = cnt;
    }
    return agents;
}

void agy_get_stats(uint32_t *active_agents, uint32_t *tasks_done, uint64_t *tokens) {
    uint32_t active = 0;
    for (int i = 0; i < AGY_MAX_AGENTS; i++) {
        if (agents[i].state == AGENT_THINKING || 
            agents[i].state == AGENT_RUNNING || 
            agents[i].state == AGENT_WAITING) {
            active++;
        }
    }
    agy_orchestrator.active_agents = active;

    if (active_agents) *active_agents = agy_orchestrator.active_agents;
    if (tasks_done)    *tasks_done    = agy_orchestrator.tasks_done;
    if (tokens)        *tokens        = agy_orchestrator.total_tokens;
}

void agy_step_all(void) {
    uint32_t active = 0;
    for (int i = 0; i < AGY_MAX_AGENTS; i++) {
        struct agy_agent *a = &agents[i];
        if (a->state == AGENT_UNUSED) continue;

        if (a->state == AGENT_THINKING || a->state == AGENT_RUNNING || a->state == AGENT_WAITING) {
            active++;
            /* If no task is driving this agent, step it synchronously */
            if (a->pid <= 0) {
                if (a->state == AGENT_THINKING) {
                    a->state = AGENT_RUNNING;
                    a->last_tick = timer_get_ticks();
                    agy_orchestrator.total_tokens += 480;
                    strncpy(a->last_message, "Decomposing goal and preparing execution", sizeof(a->last_message) - 1);
                    a->last_message[sizeof(a->last_message) - 1] = '\0';
                } else if (a->state == AGENT_RUNNING) {
                    a->steps_done++;
                    a->last_tick = timer_get_ticks();
                    agy_orchestrator.total_tokens += 320;
                    if (a->steps_done >= a->steps_total) {
                        a->state = AGENT_COMPLETED;
                        agy_orchestrator.total_tokens += 220;
                        agy_orchestrator.tasks_done++;
                        agy_generate_artifact(a);
                        strncpy(a->last_message, "Goal completed. Artifact saved to ramfs.", sizeof(a->last_message) - 1);
                        a->last_message[sizeof(a->last_message) - 1] = '\0';
                    }
                }
            }
        }
    }
    agy_orchestrator.active_agents = active;

    /* Yield CPU to let active agent threads execute */
    if (active > 0) {
        task_yield();
    }
}
